/**
 * Decode 8-bit μ-law (PCMU) encoded audio to 16-bit linear PCM.
 *
 * @param data - Uint8Array of 8-bit μ-law samples
 * @returns Int16Array of 16-bit linear PCM samples
 */
export function decodeMuLaw(data: Uint8Array): Int16Array {
  const out = new Int16Array(data.length);
  for (let i = 0; i < data.length; i++) {
    // μ-law uses bitwise NOT of the 8-bit value for indexing
    out[i] = MU_LAW_TABLE[data[i]];
  }
  return out;
}

/**
 * Decode 8-bit A-law (PCMA) encoded audio to 16-bit linear PCM.
 *
 * @param data - Uint8Array of 8-bit A-law samples
 * @returns Int16Array of 16-bit linear PCM samples
 */
export function decodeALaw(data: Uint8Array): Int16Array {
  const out = new Int16Array(data.length);
  for (let i = 0; i < data.length; i++) {
    // A-law XORs bit 0x55 (alternating bit pattern) before indexing
    out[i] = A_LAW_TABLE[data[i] ^ 0x55];
  }
  return out;
}
